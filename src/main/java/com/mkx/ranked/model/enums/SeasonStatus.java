package com.mkx.ranked.model.enums;

/**
 * Статус рейтингового сезона.
 */
public enum SeasonStatus {

    /**
     * Сезон создан, но ещё не запущен.
     */
    CREATED,

    /**
     * Сезон активен.
     * В этом состоянии разрешено проведение рейтинговых матчей.
     */
    ACTIVE,

    /**
     * Сезон завершён.
     * Новые рейтинговые матчи больше не принимаются.
     */
    FINISHED
}